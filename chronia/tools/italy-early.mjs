export const timelineOf = (text) => text.split(";").map((t) => t.trim()).map((t, i) => {
  const m = /^(?:(-?\d+) )?([A-Za-z0-9]+)(?:\/([A-Z]+))?$/.exec(t);
  if (!m || (i && m[1] == null) || (!i && m[1] != null)) throw new Error("italy: bad timeline entry " + JSON.stringify(t) + " in " + JSON.stringify(text));
  if (m[2] !== "ROM" && !OWNERS[m[2]]) throw new Error("italy: unknown owner " + m[2]);
  return { from: i ? Number(m[1]) : -Infinity, owner: m[2], ruler: m[3] || "" };
});

const attrsAt = ({ owner, ruler }, y) => {
  const rulerName = ruler ? (y <= ROME_KINGDOM_TO ? "Roman Kingdom" : "Roman Republic") : "";
  if (owner === "ROM") { const name = y <= ROME_KINGDOM_TO ? "Roman Kingdom" : "Roman Republic"; return { name, wiki: name, people: 0, part: "", ruler: "", status: 0 }; }
  const [name, wiki, o] = OWNERS[owner];
  const people = !ruler && o.people && (o.peopleTo == null || y <= o.peopleTo) ? 1 : 0;
  const part = !ruler && o.league && y >= LEAGUE_FROM && y <= LEAGUE_TO ? LATIN_LEAGUE : "";
  return { name, wiki, people, part, ruler: rulerName, status: ruler ? 5 : 0 };
};

export const buildItaly = ({ topo, client, rewind }) => {
  const geoms = topo.objects.zones.geometries, byKey = new Map(geoms.map((g, i) => [g.properties.k, i]));
  for (const [k] of ZONES) if (!byKey.has(k)) throw new Error("italy: no zone " + k + " in italy-zones.json; run tools/italy-zones.mjs");
  const lines = ZONES.map(([k, , text]) => ({ i: byKey.get(k), steps: timelineOf(text) }));
  const merged = new Map();
  const shape = (ix) => { const key = ix.join(","); if (!merged.has(key)) merged.set(key, rewind(client.merge(topo, ix.map((i) => geoms[i])).coordinates)); return merged.get(key); };
  const spans = [];
  let open = new Map();
  for (let y = ITALY_FROM; y <= ITALY_TO; y++) {
    const groups = new Map();
    for (const { i, steps } of lines) {
      const step = steps.filter((s) => s.from <= y).pop();
      const a = attrsAt(step, y), key = JSON.stringify(a);
      if (!groups.has(key)) groups.set(key, { a, ix: [] });
      groups.get(key).ix.push(i);
    }
    const next = new Map();
    for (const [key, { a, ix }] of groups) {
      const run = key + "|" + ix.sort((p, q) => p - q).join(",");
      const s = open.get(run);
      if (s) { s.last = y; next.set(run, s); continue; }
      const t = { ...a, b: 1, first: y, last: y, ix };
      spans.push(t);
      next.set(run, t);
    }
    open = next;
  }
  const out = spans.map(({ ix, ...s }) => ({ ...s, polys: shape(ix) }));
  const mask = rewind(client.merge(topo, geoms).coordinates);
  return { spans: out, mask, zones: geoms.length };
};
